#!/usr/bin/env bash
# Sandbox test for spx-boot: fake /boot, DTBs, device tree and ESP under a temp dir.
# Never touches the real ESP or UEFI variables (SPX_PREFIX set => no efibootmgr calls).
set -uo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
T=$(mktemp -d); trap 'rm -rf "$T"' EXIT
export SPX_PREFIX=$T/root SPX_DT=$T/dt SPX_ESP=$T/esp SPX_ROOT_UUID=11111111-2222-3333-4444-555555555555 SPX_LIBDIR=$T/lib
SB="bash $HERE/spx-boot"
fail=0; ok() { echo "ok   - $1"; }; bad() { echo "FAIL - $1"; fail=1; }

mkdir -p $SPX_PREFIX/boot $SPX_PREFIX/etc/default $SPX_PREFIX/var/lib $T/dt $T/esp/EFI/Microsoft/Boot $T/lib
printf 'microsoft,cambria\0qcom,sc8180x\0' > $T/dt/compatible
echo fake > $T/esp/EFI/Microsoft/Boot/bootmgfw.efi
echo fakegrub > $T/lib/grubaa64.efi
mkk() {  # $1 release, $2 image magic (MZ or gzip)
  if [ "$2" = MZ ]; then printf 'MZfake' > $SPX_PREFIX/boot/vmlinuz-$1; else printf '\x1f\x8bfake' > $SPX_PREFIX/boot/vmlinuz-$1; fi
  echo initrd > $SPX_PREFIX/boot/initrd.img-$1
  mkdir -p $SPX_PREFIX/usr/lib/linux-image-$1/qcom; echo dtb > $SPX_PREFIX/usr/lib/linux-image-$1/qcom/sc8180x-microsoft-cambria.dtb
}
mkk 7.4.0-rc2-next-20261109-spx6 MZ
mkk 7.4.0-rc2-next-20261109-spx7 MZ
mkk 7.4.0-rc1-other gz                     # compressed: must be skipped
printf 'MZ' > $SPX_PREFIX/boot/vmlinuz-7.4.0-noinitrd   # no initrd: must be skipped

out=$($SB print-config 2>$T/err) || bad "print-config failed: $(cat $T/err)"
echo "$out" | head -1 | grep -q '^# generated by spx-boot' && ok "marker line" || bad "marker line"
[ "$(echo "$out" | grep -c '^menuentry')" = 5 ] && ok "5 entries (2 kernels, safe, Windows, UEFI)" || bad "entry count: $(echo "$out" | grep -c '^menuentry')"
echo "$out" | grep -A5 '^menuentry "SPX Linux" {' | grep -q 'vmlinuz-7.4.0-rc2-next-20261109-spx7 ' && ok "newest kernel is the default" || bad "newest kernel not default"
echo "$out" | grep -q 'previous kernel 7.4.0-rc2-next-20261109-spx6' && ok "previous kernel entry" || bad "previous entry"
echo "$out" | grep -q 'rc1-other' && bad "compressed kernel was listed" || ok "compressed Image.gz skipped"
grep -q 'not an uncompressed' $T/err && ok "warned about Image.gz" || bad "no Image.gz warning"
echo "$out" | grep -q 'deferred_probe_timeout=60' && ok "required cmdline present" || bad "cmdline"
echo "$out" | grep -q "search --no-floppy --fs-uuid $SPX_ROOT_UUID" && ok "root found by fs UUID" || bad "uuid search"
echo "$out" | grep -q 'devicetree /usr/lib/linux-image-7.4.0-rc2-next-20261109-spx7/qcom/sc8180x-microsoft-cambria.dtb' && ok "DTB path" || bad "DTB path"
echo "$out" | grep -q $'\r' && bad "CR in output" || ok "LF only"

# update before install: silent no-op
$SB update && [ ! -e $T/esp/EFI/spx/grub.cfg ] && ok "update is a no-op before install" || bad "update wrote before install"

# install refuses a foreign grub.cfg without --adopt
mkdir -p $T/esp/EFI/spx; echo 'menuentry "hand made" {}' > $T/esp/EFI/spx/grub.cfg
$SB install --yes >/dev/null 2>&1 && bad "installed over a foreign grub.cfg" || ok "refuses foreign grub.cfg without --adopt"
grep -q 'hand made' $T/esp/EFI/spx/grub.cfg && ok "foreign grub.cfg untouched" || bad "foreign grub.cfg changed"

# dry run changes nothing
$SB install --adopt --dry-run >/dev/null 2>&1; grep -q 'hand made' $T/esp/EFI/spx/grub.cfg && [ ! -e $SPX_PREFIX/var/lib/spx-boot/state ] && ok "dry run changes nothing" || bad "dry run changed something"

# adopt
$SB install --adopt --yes >/dev/null 2>$T/err || bad "install --adopt failed: $(cat $T/err)"
grep -q 'hand made' $T/esp/EFI/spx/backup-before-spx-boot/grub.cfg && ok "backup of the old grub.cfg" || bad "no backup"
head -1 $T/esp/EFI/spx/grub.cfg | grep -q 'generated by spx-boot' && ok "grub.cfg written" || bad "grub.cfg not written"
cmp -s $T/esp/EFI/spx/grubaa64.efi $T/lib/grubaa64.efi && ok "grubaa64.efi installed" || bad "grubaa64.efi"
[ "$(wc -c < $T/esp/EFI/spx/grubenv)" = 1024 ] && ok "grubenv is 1024 bytes" || bad "grubenv size"
[ -f $SPX_PREFIX/var/lib/spx-boot/state ] && ok "state recorded" || bad "no state"
[ -f $T/esp/EFI/Microsoft/Boot/bootmgfw.efi ] && [ "$(ls $T/esp/EFI)" = "$(printf 'Microsoft\nspx')" ] && ok "nothing outside \\EFI\\spx touched" || bad "ESP contents: $(ls $T/esp/EFI)"

# a new kernel arrives: update picks it up, keeps 2, saves .prev
mkk 7.4.0-rc3-next-20261201-spx8 MZ
$SB update 2>/dev/null
grep -A5 '^menuentry "SPX Linux" {' $T/esp/EFI/spx/grub.cfg | grep -q 'spx8 ' && ok "update: new kernel is default" || bad "update: new kernel"
grep -q 'spx6' $T/esp/EFI/spx/grub.cfg && bad "update: kept more than SPX_KEEP=2" || ok "update: keeps 2 kernels"
[ -f $T/esp/EFI/spx/grub.cfg.prev ] && ok "update: previous menu saved" || bad "no grub.cfg.prev"

# kernel removed (postrm): menu follows
rm $SPX_PREFIX/boot/vmlinuz-7.4.0-rc3-next-20261201-spx8
$SB update 2>/dev/null
grep -q spx8 $T/esp/EFI/spx/grub.cfg && bad "removed kernel still listed" || ok "removed kernel dropped"

# test mode: separate \EFI\spx-test, spx.test=1, own state file, main install untouched
cp $T/esp/EFI/spx/grub.cfg $T/main.cfg
$SB install --test --yes >/dev/null 2>$T/err || bad "install --test failed: $(cat $T/err)"
[ -f $T/esp/EFI/spx-test/grub.cfg ] && ok "test install writes \\EFI\\spx-test" || bad "no spx-test grub.cfg"
grep -q 'search --no-floppy --file /EFI/spx-test/grub.cfg' $T/esp/EFI/spx-test/grub.cfg && ok "test menu finds itself in spx-test" || bad "test menu path"
grep -A6 '^menuentry "SPX Linux" {' $T/esp/EFI/spx-test/grub.cfg | grep -q 'spx.test=1' && ok "test kernels get spx.test=1" || bad "no spx.test=1"
cmp -s $T/main.cfg $T/esp/EFI/spx/grub.cfg && ok "main \\EFI\\spx untouched by test install" || bad "main menu changed"
[ -f $SPX_PREFIX/var/lib/spx-boot/state-test ] && ok "test state is separate" || bad "no state-test"
$SB install --test --make-default --yes >/dev/null 2>&1 && bad "accepted --test --make-default" || ok "refuses --test --make-default"
$SB remove --test --yes >/dev/null 2>&1 || bad "remove --test failed"
[ ! -e $T/esp/EFI/spx-test ] && [ ! -e $SPX_PREFIX/var/lib/spx-boot/state-test ] && ok "remove --test cleans up" || bad "remove --test left files"
[ -f $T/esp/EFI/spx/grub.cfg ] && [ -f $SPX_PREFIX/var/lib/spx-boot/state ] && ok "remove --test leaves the main install" || bad "main install damaged"
# remove refuses a foreign grub.cfg
mkdir -p $T/esp/EFI/spx-test; echo 'foreign' > $T/esp/EFI/spx-test/grub.cfg; echo "ESP_PARTUUID=test" > $SPX_PREFIX/var/lib/spx-boot/state-test
$SB remove --test --yes >/dev/null 2>&1 && bad "removed a foreign grub.cfg" || ok "remove refuses a foreign grub.cfg"
rm -rf $T/esp/EFI/spx-test $SPX_PREFIX/var/lib/spx-boot/state-test

# unknown machine refuses
printf 'acme,laptop\0' > $T/dt/compatible
$SB print-config >/dev/null 2>&1 && bad "accepted an unknown machine" || ok "refuses unknown machine"

echo; [ $fail = 0 ] && echo "ALL TESTS PASSED" || { echo "SOME TESTS FAILED"; exit 1; }
